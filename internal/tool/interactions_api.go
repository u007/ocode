// The Gemini Interactions API (POST /v1beta/interactions) generates video and
// audio. It is a different endpoint from the generateContent API used by
// imagegen, so the helpers here are shared by videogen and audiogen only.
const (
	defaultGenerativeBaseURL = "https://generativelanguage.googleapis.com"
	maxInteractionResponse   = maxAPIResponseBytes
)

// interactionPart is one content block of an Interactions API response. Only
// the fields ocode reads are decoded; text parts are kept for error context.
type interactionPart struct {
	Type     string `json:"type"`
	Text     string `json:"text"`
	MimeType string `json:"mime_type"`
	Data     string `json:"data"`
}

// callGeminiInteraction posts one Interactions API request and returns the
// model_output content parts. body must already contain "model" and "input".
func callGeminiInteraction(ctx context.Context, baseURL, apiKey string, body map[string]any) ([]interactionPart, string, error) {
	payload, err := json.Marshal(body)
	if err != nil {
		return nil, "", fmt.Errorf("marshal request: %w", err)
	}

	endpoint := strings.TrimRight(baseURL, "/") + "/v1beta/interactions"
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, endpoint, bytes.NewReader(payload))
	if err != nil {
		return nil, "", fmt.Errorf("build request: %w", err)
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("x-goog-api-key", apiKey)

	resp, err := credentialedHTTPClient.Do(req)
	if err != nil {
		return nil, "", fmt.Errorf("gemini interactions request failed: %w", err)
	}
	defer resp.Body.Close()

	respBody, over, rerr := readCappedBody(resp.Body, maxInteractionResponse)
	if rerr != nil {
		return nil, "", fmt.Errorf("read gemini interactions response: %w", rerr)
	}
	if over {
		return nil, "", fmt.Errorf("gemini interactions response exceeds the %d-byte response cap", maxInteractionResponse)
	}
	if resp.StatusCode != http.StatusOK {
		return nil, "", fmt.Errorf("gemini interactions error (%d): %s", resp.StatusCode, truncateErr(respBody))
	}

	var parsed struct {
		Steps []struct {
			Type    string            `json:"type"`
			Content []interactionPart `json:"content"`
		} `json:"steps"`
		Status string `json:"status"`
		Error  *struct {
			Code    int    `json:"code"`
			Message string `json:"message"`
		} `json:"error"`
	}
	if err := json.Unmarshal(respBody, &parsed); err != nil {
		return nil, "", fmt.Errorf("parse gemini interactions response: %w", err)
	}
	if parsed.Error != nil && parsed.Error.Message != "" {
		return nil, "", fmt.Errorf("gemini interactions error: %s", parsed.Error.Message)
	}

	var parts []interactionPart
	for _, step := range parsed.Steps {
		if step.Type != "model_output" {
			continue
		}
		parts = append(parts, step.Content...)
	}
	if len(parts) == 0 {
		return nil, parsed.Status, fmt.Errorf("gemini returned no model output (status %q)", parsed.Status)
	}
	return parts, parsed.Status, nil
}

// lastInteractionData returns the decoded bytes of the last part of the given
// type (video/audio) and its MIME type.
func lastInteractionData(parts []interactionPart, wantType string) ([]byte, string, error) {
	var (
		data []byte
		mime string
	)
	for _, part := range parts {
		if part.Type != wantType || part.Data == "" {
			continue
		}
		decoded, err := base64.StdEncoding.DecodeString(part.Data)
		if err != nil {
			return nil, "", fmt.Errorf("decode %s data: %w", wantType, err)
		}
		data = decoded
		mime = part.MimeType
	}
	if data == nil {
		return nil, "", fmt.Errorf("gemini returned no %s output", wantType)
	}
	return data, mime, nil
}

// saveMediaFile writes generated bytes to outputPath (a directory, a file path,
// or "" for the working directory with defaultName) and returns the path.
func saveMediaFile(ctx context.Context, outputPath, defaultName, ext string, data []byte) (string, error) {
	wd, err := os.Getwd()
	if err != nil {
		return "", fmt.Errorf("working directory: %w", err)
	}

	base := outputPath
	if base == "" {
		base = filepath.Join(wd, defaultName)
	} else if confined, cerr := confinedPath(ctx, base); cerr != nil {
		// Not inside an allowed root: treat it as a name under the working dir.
		base = filepath.Join(wd, filepath.Base(base))
	} else {
		base = confined
	}

	if info, statErr := os.Stat(base); statErr == nil && info.IsDir() {
		base = filepath.Join(base, defaultName)
	}
	path := withExt(base, ext)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", fmt.Errorf("create output dir: %w", err)
	}
	if err := os.WriteFile(path, data, 0o644); err != nil {
		return "", fmt.Errorf("write %s: %w", filepath.Base(path), err)
	}
	return path, nil
}

// credentialedHTTPClient sends every request that carries a provider API key.
// It refuses redirects: the stored key rides in a custom header (x-goog-api-key,
// or a bearer token), and Go copies custom headers onto the redirect target, so
// a 3xx from the endpoint would hand the key to whatever host it names. The 3xx
// is returned as the response and fails each caller's status check.
var credentialedHTTPClient = &http.Client{
	CheckRedirect: func(*http.Request, []*http.Request) error {
		return http.ErrUseLastResponse
	},
}

// requireExplicitKeyForBaseURL keeps a stored provider key away from a base_url
// the caller chose. Naming a base_url without an api_key is refused: the stored
// key is only ever sent to the configured endpoint (or the provider default).
func requireExplicitKeyForBaseURL(baseURL, apiKey string) error {
	if strings.TrimSpace(baseURL) == "" || strings.TrimSpace(apiKey) != "" {
		return nil
	}
	msg := "custom base_url requires an explicit api_key: the stored key is only sent to the configured endpoint"
	return &NoticedError{Err: errors.New(msg), Notice: msg}
}

// geminiGenerativeCredentials resolves the Gemini API key and base URL from the
// same sources imagegen uses (param > stored credential base URL > default).
func geminiGenerativeCredentials(apiKey, baseURL string) (string, string, error) {
	if err := requireExplicitKeyForBaseURL(baseURL, apiKey); err != nil {
		return "", "", err
	}
	_ = auth.LoadStore()
	// The auth provider id is "google" (GOOGLE_API_KEY); imagegen normalizes
	// "gemini" to the same id. Resolving "gemini" directly finds no provider
	// and silently yields an empty key.
	if apiKey == "" {
		apiKey = auth.ResolveKey("google")
	}
	if apiKey == "" {
		return "", "", &NoticedError{
			Err:    fmt.Errorf("no API key for provider %q", "google"),
			Notice: "No Gemini API key found. Set GOOGLE_API_KEY, configure provider.google.options.apiKey, or run /connect.",
		}
	}
	if baseURL == "" {
		baseURL = auth.GetBaseURL("google")
	}
	if baseURL == "" {
		baseURL = defaultGenerativeBaseURL
	}
	return apiKey, baseURL, nil
}
